package id.jawa.protocol.crypto;

import java.nio.charset.StandardCharsets;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.HexFormat;

/**
 * Utility functions for byte array manipulation, hexadecimal formatting, base64 conversions,
 * and secure random generation.
 */
public final class Bytes {

    private static final SecureRandom RNG = new SecureRandom();

    private Bytes() {}

    /**
     * Concatenates multiple byte arrays into a single contiguous array.
     *
     * @param parts variable array of byte arrays (null segments are ignored)
     * @return the combined byte array
     */
    public static byte[] concat(byte[]... parts) {
        int total = 0;
        for (byte[] p : parts) if (p != null) total += p.length;
        byte[] out = new byte[total];
        int pos = 0;
        for (byte[] p : parts) {
            if (p == null) continue;
            System.arraycopy(p, 0, out, pos, p.length);
            pos += p.length;
        }
        return out;
    }

    /**
     * Extracts a sub-array from src between index from (inclusive) and to (exclusive).
     *
     * @param src source byte array
     * @param from start index
     * @param to end index
     * @return slice copy
     */
    public static byte[] slice(byte[] src, int from, int to) {
        if (from < 0 || to > src.length || from > to) {
            throw new IllegalArgumentException("invalid slice [" + from + ", " + to + ") of length " + src.length);
        }
        byte[] out = new byte[to - from];
        System.arraycopy(src, from, out, 0, to - from);
        return out;
    }

    /**
     * Generates cryptographically secure pseudo-random bytes.
     *
     * @param length number of random bytes to produce
     * @return newly generated byte array
     */
    public static byte[] random(int length) {
        byte[] b = new byte[length];
        RNG.nextBytes(b);
        return b;
    }

    public static String toHex(byte[] b) {
        return HexFormat.of().formatHex(b);
    }

    public static byte[] fromHex(String s) {
        return HexFormat.of().parseHex(s);
    }

    public static String toBase64(byte[] b) {
        return Base64.getEncoder().encodeToString(b);
    }

    public static byte[] fromBase64(String s) {
        return Base64.getDecoder().decode(s);
    }

    public static String toBase64Url(byte[] b) {
        return Base64.getUrlEncoder().withoutPadding().encodeToString(b);
    }

    public static byte[] fromBase64Url(String s) {
        return Base64.getUrlDecoder().decode(s);
    }

    public static byte[] utf8(String s) {
        return s.getBytes(StandardCharsets.UTF_8);
    }

    public static String fromUtf8(byte[] b) {
        return new String(b, StandardCharsets.UTF_8);
    }
}
